function extractPhrases(text) {
  const library = [
    ["specific knowledge", "特殊知识"],
    ["permissionless leverage", "无需许可的杠杆"],
    ["long-term games", "长期游戏"],
    ["status games", "地位游戏"],
    ["first principles", "第一性原理"],
    ["compound interest", "复利"],
    ["upside", "上行空间"],
    ["downside", "下行风险"],
    ["market feedback", "市场反馈"],
    ["revealed preference", "显示性偏好"],
    ["regulatory risk", "监管风险"],
    ["venture capital", "风险投资"],
    ["seed round", "种子轮融资"],
    ["product-market fit", "产品市场匹配"],
    ["founder-market fit", "创始人与市场匹配"],
    ["artificial intelligence", "人工智能"],
    ["language model", "语言模型"],
    ["capital allocation", "资本配置"],
    ["decision-making", "决策"],
    ["mental models", "思维模型"]
  ];

  const lowered = text.toLowerCase();
  const hits = library.filter(([en]) => lowered.includes(en.toLowerCase()));
  if (hits.length >= 5) return hits.slice(0, 8);

  const words = text
    .replace(/[^A-Za-z\s-]/g, " ")
    .split(/\s+/)
    .filter((word) => word.length > 6);
  const counts = new Map();
  words.forEach((word) => counts.set(word.toLowerCase(), (counts.get(word.toLowerCase()) || 0) + 1));
  const generated = [...counts.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 8 - hits.length)
    .map(([word]) => [word, "视频关键词，建议交给豆包解释使用场景"]);
  return [...hits, ...generated].slice(0, 8);
}

async function copyDoubaoPrompt() {
  const text = document.getElementById("clipText").value.trim();
  const prompt = `${doubaoBasePrompt}\n\n${text || "请在这里粘贴英文字幕或英文文章片段。"}`;
  try {
    await navigator.clipboard.writeText(prompt);
    showToast("豆包提示词已复制。");
  } catch {
    showToast("复制失败，可以手动选中文字复制。");
  }
}

document.addEventListener("click", (event) => {
  const speakButton = event.target.closest("[data-speak]");
  if (speakButton) {
    speak(speakButton.dataset.speak, Number(speakButton.dataset.rate || 0.86));
    return;
  }

  const phraseButton = event.target.closest("[data-save-phrase]");
  if (phraseButton) {
    savePhrase(phraseButton.dataset.savePhrase, phraseButton.dataset.meaning);
    return;
  }

  const removeButton = event.target.closest("[data-remove-phrase]");
  if (removeButton) {
    state.phrases.splice(Number(removeButton.dataset.removePhrase), 1);
    saveState();
    renderPhrases();
    renderReview();
    showToast("已删除。");
    return;
  }

  const reviewButton = event.target.closest("[data-review-done]");
  if (reviewButton) {
    state.reviewLog[reviewButton.dataset.reviewDone] = new Date().toDateString();
    saveState();
    renderReview();
    showToast("今天已复习。");
    return;
  }

  const lessonButton = event.target.closest("[data-open-lesson]");
  if (lessonButton) {
    selectedLessonDay = Number(lessonButton.dataset.openLesson);
    state.selectedLessonDay = selectedLessonDay;
    saveState();
    renderAll();
    openView("todayView");
    return;
  }

  const navButton = event.target.closest("[data-view]");
  if (navButton) {
    openView(navButton.dataset.view);
    return;
  }

  const sessionButton = event.target.closest("[data-session]");
  if (sessionButton) {
    state.sessionMinutes = Number(sessionButton.dataset.session);
    saveState();
    renderAll();
    showToast(`已切换为 ${state.sessionMinutes} 分钟节奏。`);
    return;
  }

  if (event.target.closest("#completeLessonButton")) {
    completeCurrentLesson();
    return;
  }

  if (event.target.closest("#nextLessonButton")) {
    goNextLesson();
  }
});

