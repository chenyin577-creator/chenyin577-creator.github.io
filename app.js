function loadState() {
  const defaults = {
    completed: {},
    notes: {},
    phrases: [],
    selectedLessonDay: 1,
    sessionMinutes: 10,
    reviewLog: {}
  };

  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY));
    return { ...defaults, ...saved };
  } catch {
    return defaults;
  }
}

function saveState() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
}

function getFirstOpenDay() {
  const first = LESSONS.find((lesson) => !state.completed[String(lesson.day)]);
  return first ? first.day : 30;
}

function getLesson(day) {
  return LESSONS.find((lesson) => lesson.day === Number(day)) || LESSONS[0];
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function showToast(message) {
  window.clearTimeout(toastTimer);
  toast.textContent = message;
  toast.classList.add("show");
  toastTimer = window.setTimeout(() => toast.classList.remove("show"), 2200);
}

function speak(text, rate = 0.86) {
  if (!("speechSynthesis" in window)) {
    showToast("这个浏览器暂时不能朗读。");
    return;
  }

  window.speechSynthesis.cancel();
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = "en-US";
  utterance.rate = rate;
  utterance.pitch = 1;
  const voices = window.speechSynthesis.getVoices();
  const preferred = voices.find((voice) => /Samantha|Ava|Allison|Daniel|Karen|Google US English/i.test(voice.name));
  if (preferred) utterance.voice = preferred;
  window.speechSynthesis.speak(utterance);
}

